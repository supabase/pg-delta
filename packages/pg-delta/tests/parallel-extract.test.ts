/**
 * Opt-in bounded-parallel extraction (`ExtractOptions.concurrency`).
 *
 * The contract under test is EQUIVALENCE, not speed: N catalog-query streams
 * sharing the coordinator's `pg_export_snapshot()` must reproduce the serial
 * extraction byte-for-byte — same FactBase rootHash, same fact order, same edge
 * order, same diagnostics order — because the scheduler slots per-family results
 * by family index and merges in the fixed call order, never completion order.
 *
 * Everything else here is about not hurting anyone: never queue on an exhausted
 * pool (that would deadlock, since the coordinator holds a client while asking
 * for more), degrade silently to serial when the snapshot cannot be shared, and
 * leak no client / open transaction on any error path.
 */
